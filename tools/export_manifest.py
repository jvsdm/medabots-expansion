"""
export_manifest.py - Gera o manifesto da expansao para o Toolkit (C#).

O Toolkit monta a ROM expandida a partir de duas ROMs fornecidas pelo usuario (Metabee EU e
Shingata Kabuto). O manifesto so traz o que NAO esta nelas:
  - bots novos que nao vem de outra ROM (Sagehorn): nomes + stats + bot EU de onde copiar graficos;
  - bots do Shingata: ordem (indice no Shingata) + nomes da Medapedia (stats/graficos saem da ROM).
Os 120 originais saem inteiros da ROM EU (conferido: data/bots 0-119 == ROM).

Saida: git/Medabots-Romhacking-Toolkit/src/Medabots.Rom/Expansion/expansion.manifest.json
"""
import json
from medarom import ROOT, BOT_COUNT, PART_KINDS, part_fields

OUT = ROOT / "git" / "Medabots-Romhacking-Toolkit" / "src" / "Medabots.Rom" / "Expansion" / "expansion.manifest.json"
DEFAULT_GFX_FROM = 43


def main():
    bots = [json.loads(f.read_text(encoding="utf-8")) for f in sorted((ROOT / "data" / "bots").glob("*.json"))]
    entries = []
    for b in bots[BOT_COUNT:]:
        if b.get("local_only"):
            continue                     # teste com arte local: fica fora do Toolkit
        names = [b["parts"][k]["name"] for k in PART_KINDS]
        gs = b.get("graphics_source")
        if gs and "Shingata" in gs["rom"]:
            if set(gs) - {"rom", "bot", "tables"}:
                raise SystemExit(f"{b['name']}: opcoes de graphics_source nao suportadas no manifesto")
            entries.append({"id": b["bot_id"], "name": b["name"], "partNames": names, "shingataBot": gs["bot"]})
        elif gs:
            raise SystemExit(f"{b['name']}: graphics_source de outra ROM nao suportado")
        else:
            stats = [[b["parts"][k]["stats"][f] for f in part_fields(k)] for k in PART_KINDS]
            entry = {"id": b["bot_id"], "name": b["name"], "partNames": names, "stats": stats,
                     "graphicsFrom": b.get("graphics_from", DEFAULT_GFX_FROM)}
            if "recolor" in b:
                entry["recolor"] = b["recolor"]
            entries.append(entry)
    manifest = {
        "comment": "Generated by tools/export_manifest.py. Bots 0-119 come from the Metabee (E) ROM; "
                   "Shingata bots take stats and graphics from the Shingata Medarot Kabuto ROM. "
                   "Shingata names: Medapedia.",
        "bots": entries,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(entries)} bots novos -> {OUT}")


if __name__ == "__main__":
    main()
